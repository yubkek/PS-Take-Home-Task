import { provideHttpClient } from '@angular/common/http';
import { HttpTestingController, provideHttpClientTesting } from '@angular/common/http/testing';
import { TestBed } from '@angular/core/testing';
import { Summary } from '../candidate';
import { SummaryPanel } from './summary-panel';

const summary: Summary = {
  status: 'ok',
  headline: 'An engineer with two years of experience.',
  skills: ['TypeScript'],
  highlights: ['Built a dashboard'],
  warnings: [],
  model: 'openai/gpt-oss-120b',
  generatedAt: '2026-01-01T00:00:00.000Z',
};

describe('SummaryPanel', () => {
  let http: HttpTestingController;

  beforeEach(() => {
    TestBed.configureTestingModule({ providers: [provideHttpClient(), provideHttpClientTesting()] });
    http = TestBed.inject(HttpTestingController);
  });
  afterEach(() => http.verify());

  async function render(initial: Summary | null) {
    const fixture = TestBed.createComponent(SummaryPanel);
    fixture.componentRef.setInput('candidateId', 7);
    fixture.componentRef.setInput('initial', initial);
    fixture.detectChanges();
    return { fixture, el: fixture.nativeElement as HTMLElement };
  }

  it('generates once on first view when there is no summary', async () => {
    const { fixture, el } = await render(null);
    expect(el.textContent).toContain('Generating summary');

    const request = http.expectOne('/api/candidates/7/summary');
    expect(request.request.method).toBe('POST');
    request.flush(summary);
    await fixture.whenStable();

    expect(el.textContent).toContain(summary.headline);
    expect(el.textContent).not.toContain('AI-generated by');
  });

  it('shows a stored summary without calling the model again', async () => {
    const { el } = await render(summary);
    http.expectNone('/api/candidates/7/summary');
    expect(el.textContent).toContain(summary.headline);
  });

  it('keeps the current summary on screen when regenerating fails', async () => {
    const { fixture, el } = await render(summary);
    el.querySelector('button')!.click();
    fixture.detectChanges();
    http
      .expectOne('/api/candidates/7/summary')
      .flush({ error: 'The AI service is busy.' }, { status: 503, statusText: 'Unavailable' });
    await fixture.whenStable();

    expect(el.querySelector('[role=alert]')?.textContent).toContain('The AI service is busy.');
    expect(el.textContent).toContain(summary.headline);
  });

  it('shows the injection warning above the summary', async () => {
    const { el } = await render({ ...summary, warnings: ['May contain instructions aimed at AI tools.'] });
    const warning = el.querySelector('.warning')!;
    expect(warning.textContent).toContain('aimed at AI tools');
    expect(warning.compareDocumentPosition(el.querySelector('.headline')!)).toBe(Node.DOCUMENT_POSITION_FOLLOWING);
  });

  it('shows the reason and no empty sections when the text was unusable', async () => {
    const { el } = await render({
      ...summary,
      status: 'insufficient',
      headline: '',
      skills: [],
      highlights: [],
      warnings: ['Resume text looks garbled or corrupted.'],
      model: null,
    });
    expect(el.textContent).toContain('garbled');
    expect(el.textContent).toContain('No AI was used');
    expect(el.querySelector('.headline')).toBeNull();
  });

  it('renders model output as text, never as markup', async () => {
    const { el } = await render({ ...summary, headline: '<img src=x onerror=alert(1)>' });
    expect(el.querySelector('img')).toBeNull();
    expect(el.textContent).toContain('<img src=x');
  });
});
